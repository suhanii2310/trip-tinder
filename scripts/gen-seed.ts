// Prints supabase/seed.sql from src/data/places.nyc.ts.
// Run with: npm run seed:sql
import { NYC_PLACES } from "../src/data/places.nyc.ts";

const q = (v: string | null) => (v === null ? "null" : `'${v.replace(/'/g, "''")}'`);
const arr = (xs: string[]) => `array[${xs.map(q).join(", ")}]::text[]`;

const rows = NYC_PLACES.map((p) =>
  `  (${[
    q(p.id), q(p.city), q(p.name), `'${p.category}'`, q(p.area), p.lat, p.lng, p.price, p.distKm,
    p.visitMinutes, p.slot ? `'${p.slot}'` : "null", q(p.description), arr(p.tags), p.isSample,
    q(p.imageUrl), q(p.art), q(p.colorFrom), q(p.colorTo),
  ].join(", ")})`,
);

console.log(`-- Generated by scripts/gen-seed.ts from src/data/places.nyc.ts. Do not edit by hand.
insert into places (id, city, name, category, area, lat, lng, price, dist_km, visit_minutes, slot,
                    description, tags, is_sample, image_url, art, color_from, color_to)
values
${rows.join(",\n")}
on conflict (id) do update set
  city = excluded.city, name = excluded.name, category = excluded.category, area = excluded.area,
  lat = excluded.lat, lng = excluded.lng, price = excluded.price, dist_km = excluded.dist_km,
  visit_minutes = excluded.visit_minutes, slot = excluded.slot, description = excluded.description,
  tags = excluded.tags, is_sample = excluded.is_sample, image_url = excluded.image_url,
  art = excluded.art, color_from = excluded.color_from, color_to = excluded.color_to;`);
